/**
 * Build step 3: render every route to static HTML.
 *
 * Runs after `vite build` (client → dist/) and `vite build --ssr` (server → .ssr-build/).
 * Each route gets its own .html file carrying that page's title, description, canonical,
 * robots, Open Graph/Twitter tags and JSON-LD, so crawlers that do not execute JavaScript
 * still receive the full page. The sitemap is generated from the routes that actually
 * rendered as indexable, so it can never drift from the app.
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const ROOT = process.cwd()
const DIST = path.join(ROOT, process.env.PRERENDER_OUT_DIR || 'dist')
const SSR_DIR = path.join(ROOT, process.env.PRERENDER_SSR_DIR || '.ssr-build')
const SITE_URL = 'https://epineon.ai'
const SEO_BLOCK = /<!--seo:start-->[\s\S]*?<!--seo:end-->/
const ROOT_DIV = '<div id="root"></div>'

const { render, PRERENDER_PATHS, buildStructuredData } = await import(
  pathToFileURL(path.join(SSR_DIR, 'entry-server.js')).href
)

const template = await fs.readFile(path.join(DIST, 'index.html'), 'utf8')
if (!SEO_BLOCK.test(template)) throw new Error('index.html is missing the <!--seo:start--> … <!--seo:end--> block')
if (!template.includes(ROOT_DIV)) throw new Error(`index.html is missing ${ROOT_DIV}`)

const escapeAttr = (value) =>
  String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

function headFor(seo, jsonLd) {
  const meta = (attr, key, content) => `<meta ${attr}="${key}" content="${escapeAttr(content)}" />`
  const tags = [
    `<title>${escapeAttr(seo.title)}</title>`,
    meta('name', 'description', seo.description),
    seo.noindex ? meta('name', 'robots', 'noindex,nofollow') : null,
    `<link rel="canonical" href="${escapeAttr(seo.url)}" />`,
    meta('property', 'og:type', seo.type),
    meta('property', 'og:site_name', 'Epineon'),
    meta('property', 'og:title', seo.title),
    meta('property', 'og:description', seo.description),
    meta('property', 'og:url', seo.url),
    meta('property', 'og:image', seo.image),
    meta('property', 'og:image:width', '512'),
    meta('property', 'og:image:height', '512'),
    meta('property', 'og:image:alt', 'Epineon'),
    meta('name', 'twitter:card', 'summary_large_image'),
    meta('name', 'twitter:title', seo.title),
    meta('name', 'twitter:description', seo.description),
    meta('name', 'twitter:image', seo.image),
    jsonLd
      ? `<script type="application/ld+json">${JSON.stringify(jsonLd).replace(/</g, '\\u003c')}</script>`
      : null,
  ].filter(Boolean)
  return `<!--seo:start-->\n    ${tags.join('\n    ')}\n    <!--seo:end-->`
}

function outputFile(route) {
  return route === '/' ? 'index.html' : `${route.replace(/^\//, '')}.html`
}

async function writePage(route, file) {
  const { html, seo } = render(route)
  if (!seo.url) throw new Error(`${route}: no <Seo> rendered — the page must use PageShell or render <Seo>`)
  if (!html.includes('<h1')) throw new Error(`${route}: rendered HTML has no <h1>`)

  const page = template
    .replace(SEO_BLOCK, () => headFor(seo, buildStructuredData(seo)))
    .replace(ROOT_DIV, () => `<div id="root">${html}</div>`)

  const target = path.join(DIST, file)
  await fs.mkdir(path.dirname(target), { recursive: true })
  await fs.writeFile(target, page)
  return seo
}

const routes = [...new Set(PRERENDER_PATHS)]
if (routes.length !== PRERENDER_PATHS.length) throw new Error('PRERENDER_PATHS contains duplicates')

const indexable = []
for (const route of routes) {
  const seo = await writePage(route, outputFile(route))
  if (seo.url !== `${SITE_URL}${route}`) {
    throw new Error(`${route}: canonical ${seo.url} does not match its own URL — check the page's path prop`)
  }
  if (!seo.noindex) indexable.push(seo.url)
}

// Unknown URLs get a real 404 (no SPA fallback), served by Vercel and Cloudflare Pages alike.
await writePage('/404', '404.html')

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/prerender.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${indexable.map((url) => `  <url><loc>${url}</loc></url>`).join('\n')}
</urlset>
`
await fs.writeFile(path.join(DIST, 'sitemap.xml'), sitemap)
await fs.rm(SSR_DIR, { recursive: true, force: true })

console.log(`prerender: ${routes.length + 1} pages (${indexable.length} indexable in sitemap.xml)`)
